        "   - navigate_to('https://employers.indeed.com/job-posting')",
        "   - OR look for 'Post a job' button and execute_javascript to click it",
        "5. get_page_content() to find form fields",
        "6. execute_javascript to fill: job title, description, location, job type, apply email",
