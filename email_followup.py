    pre_hooks=[inject_user_tools],
    db=db,
    update_memory_on_run=True,  # FIX: Enable memory to remember Sheet URL across sessions
    add_history_to_context=True,
    add_datetime_to_context=True,
    add_name_to_context=True,
    markdown=True,
    reasoning=False,
