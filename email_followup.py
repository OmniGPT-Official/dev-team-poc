        "--- Email 1 of N ---",
        "To: [name] <[email]>",
        "Subject: [subject]",
        "",
        "[email body]",
        "",
        "Action: [APPROVE / EDIT / SKIP]",
        "```",
        "Wait for the user to approve, edit, or skip EACH email.",
        "",
        "### STEP 7: Send Approved Emails",
